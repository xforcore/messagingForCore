// build generated System.Messaging's Res class from it: one constant per string name, and the lookups Microsoft's code
// calls (Res.GetString, Res.GetObject). Run it again when the .txt changes:
//   dotnet run tools/generate-res.cs
#:property NuGetAudit=false
#:property PublishAot=false
using System.Text;
using System.Text.RegularExpressions;

var root = Path.GetFullPath(Path.Combine(AppContext.GetData("EntryPointFileDirectoryPath") as string ?? ".", ".."));
var txt = Path.Combine(root, "external/referencesource/System.Messaging/System.Messaging.txt");
var output = Path.Combine(root, "src/messagingForCore.System.Messaging/Res.g.cs");

var names = new List<string>();
foreach (var line in File.ReadLines(txt))
{
    var l = line.Trim();
    if (l.Length == 0 || l.StartsWith(';') || l.StartsWith('#') || l.StartsWith('[')) continue;
    var eq = l.IndexOf('=');
    if (eq <= 0) continue;
    var name = l[..eq].Trim();
    if (!Regex.IsMatch(name, @"^[A-Za-z_][A-Za-z0-9_]*$")) throw new InvalidDataException($"Not a C# name: {name}");
    if (!names.Contains(name)) names.Add(name);
}

var sb = new StringBuilder();
sb.Append("""
// <auto-generated>
// Generated by tools/generate-res.cs from external/referencesource/System.Messaging/System.Messaging.txt; don't edit.
// .NET Framework's build generated this class (System.Messaging.Res) from the same file.
// </auto-generated>
using System.Globalization;
using System.Resources;
using System.Threading;

namespace System.Messaging
{
    internal sealed class Res
    {

""");
foreach (var n in names) sb.Append($"        internal const string {n} = \"{n}\";\n");
sb.Append("""

        private static Res loader;
        private readonly ResourceManager resources;

        private Res()
        {
            resources = new ResourceManager("System.Messaging", typeof(Res).Assembly);
        }

        private static Res GetLoader()
        {
            if (loader == null)
                Interlocked.CompareExchange(ref loader, new Res(), null);
            return loader;
        }

        public static ResourceManager Resources => GetLoader().resources;

        public static string GetString(string name, params object[] args)
        {
            string format = GetLoader().resources.GetString(name, null);
            if (args == null || args.Length == 0)
                return format;
            for (int i = 0; i < args.Length; i++)
            {
                if (args[i] is string s && s.Length > 1024)
                    args[i] = s.Substring(0, 1021) + "...";
            }
            return string.Format(CultureInfo.CurrentCulture, format, args);
        }

        public static string GetString(string name) => GetLoader().resources.GetString(name, null);

        public static object GetObject(string name) => GetLoader().resources.GetObject(name, null);
    }
}

""");
File.WriteAllText(output, sb.ToString());
Console.WriteLine($"{output}: {names.Count} strings");
